#!/usr/bin/env python3
"""Generate the shelf (catalog.js) from migration/books.json and the future-volume roadmap.

Chapters and simulators are counted from each book's chapters/*.html.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
manifest = json.loads((ROOT / 'migration/books.json').read_text())
FIELDS = ('id', 'title', 'subtitle', 'headline', 'description', 'stage', 'status', 'color', 'colorDark',
          'topics', 'motif', 'code', 'slug')
catalog = []
for book in manifest['books']:
    entry = {k: book[k] for k in FIELDS}
    entry['url'] = book['slug'] + '/'
    # The individual sites are retired; readers find the books only on this shelf.
    entry['legacyUrl'] = None
    pages = list((ROOT / book['slug'] / 'chapters').glob('*.html'))
    entry['chapters'] = len(pages)
    entry['simulators'] = sum(p.read_text().count('class="sim"') for p in pages)
    catalog.append(entry)
published = len(catalog)
catalog.extend(json.loads((ROOT / 'roadmap.json').read_text()))
(ROOT / 'catalog.js').write_text('/* Generated by tools/sync-catalog.py. Text: CC BY 4.0. */\nwindow.MONEY_BOOKS = ' +
                                 json.dumps(catalog, ensure_ascii=False, indent=2) + ';\n')
print(f'Catalog: {published} published, {len(catalog) - published} planned')
